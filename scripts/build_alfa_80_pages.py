def generate_article_file(article, locale, body_content):
    title = article["title"][locale].replace('"', '\\"')
    desc = article["description"][locale].replace('"', '\\"')
    slug = article["slug"]
    date = article["date"]
    image = article["image"]
    image_alt = article.get("image_alt", title).replace('"', '\\"')
    
    tags_yaml = "\n".join([f'  - "{t}"' for t in article.get("tags", ["Wireless", "Hardware"])])
    
    faq_lines = []
    if "faq" in article:
        faq_lines.append("faq:")
        for item in article["faq"]:
            q_text = item["q"].get(locale, item["q"].get("en", "")).replace('"', '\\"')
            a_text = item["a"].get(locale, item["a"].get("en", "")).replace('"', '\\"')
            faq_lines.append(f'  - question: "{q_text}"')
            faq_lines.append(f'    answer: "{a_text}"')
    faq_yaml = "\n".join(faq_lines)
    
    fm = f"""---
title: "{title}"
date: {date}
draft: false
slug: "{slug}"
tags:
{tags_yaml}
categories:
  - "Wireless Hardware"
  - "Technical Guide"
description: "{desc}"
featureimage: "{image}"
author: "benny-lai"
lastmod: {date}
{faq_yaml}
---

![{image_alt}]({image})

{body_content}
"""
    out_dir = os.path.join(CONTENT_DIR, locale, "blog")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, f"{slug}.md")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(fm)
    print(f"[{locale}] Wrote: {out_path}")

