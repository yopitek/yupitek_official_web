def clean_source_markdown(text):
    # Remove existing frontmatter if present
    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) >= 3:
            text = parts[2]
    # Remove top level H1 if present
    text = re.sub(r"^#\s+[^\n]+\n+", "", text.strip())
    return text.strip()

